    /// <summary>Созвучие (PRD v7 §6.1, issue #79) — бонус за совпадение тегов активных артефактов. Точные значения бонусов — предмет баланса (Спринт 10).</summary>
    public enum ResonanceType
    {
        /// <summary>Жила — 3 артефакта с тегом Мана → +25% Кристаллов Маны.</summary>
        Vein,

        /// <summary>Связка Ключника — 2 артефакта с тегом Ключи → каждый 5-й добытый Ключ удваивается.</summary>
        KeyBond,

        /// <summary>Оберег — 2 артефакта с тегом Защита → первое попадание в ловушку за забег игнорируется (до d20).</summary>
        Ward,

        /// <summary>Скупой Ход — тег Жадность + тег Ход → +1 к множителю за каждый поворот маршрута.</summary>
        StingyMove,

        /// <summary>Единство — Идол и Тотем прокачаны Рунами одной линии → активная способность копится на 20% быстрее.</summary>
        Unity
    }
}
