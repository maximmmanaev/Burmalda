namespace Burmalda.Movement
{
    /// <summary>
    /// Крючок под Идолов информации (PRD v8 §4.2/6.4, issue #163) — что
    /// именно раскрывает игроку примеривание триггера ловушки
    /// (<see cref="TrapRevealSystem"/>) сверх базовой сигнатуры. Оба флага по
    /// умолчанию false — без единого Идола игрок видит только сигнатуру,
    /// которая доступна всегда и без исключений (issue #163: "информация,
    /// необходимая для честной игры, не может быть заперта за артефактом" —
    /// этот класс её не запирает, он только добавляет). Владелец,
    /// 2026-09-05 «оставить только пять новых ловушек»: понятие "скрытая
    /// ловушка" (<c>Core.TrapSignature</c>, яма/сработавший взрыв) удалено —
    /// сама ловушка теперь видна всегда, скрыт только триггер.
    ///
    /// <see cref="HasTrapContentsInsight"/> сейчас без вызывающего кода —
    /// прежний единственный потребитель (<c>DebugVisuals.TilePreviewController</c>)
    /// гейтил показ валюты на скрытой ловушке, а такая ловушка больше не
    /// существует (валюта на плите с активной ловушкой не показывается
    /// вовсе, независимо от Идола — см. doc-комментарий
    /// <c>TilePreviewController.BuildTileSummary</c>). Флаг оставлен как
    /// часть публичного API хука под Идолов (см. абзац выше) — не
    /// специфичный для трапов, для будущего подключения владельцем.
    ///
    /// <b>НЕ содержит логики "какой конкретно Idol даёт какой инсайт".</b>
    /// <see cref="Artifacts.Idol"/> сейчас безымянный (только
    /// <c>PassiveALevel</c>/<c>PassiveBLevel</c>, без привязки к конкретной
    /// роли — см. её doc-комментарий) — придумывать имена/тексты Идолов не
    /// в скоупе этой задачи (issue #163 прямо это исключает). Владелец
    /// продукта подключит сюда реальную проверку
    /// <c>Artifacts.IdolLoadout</c>, когда Идолы получат конкретную
    /// идентичность (имя/тег/роль) — не переписывая раскрытие в
    /// <c>DebugVisuals.TilePreviewController</c>, которое уже читает эти
    /// два флага.
    ///
    /// Статический класс — текущее состояние забега, читаемое несколькими
    /// независимыми системами (сейчас — только
    /// <c>DebugVisuals.TilePreviewController</c>), без протаскивания ссылки
    /// через конструкторы. Не переживает перезапуск процесса — как и
    /// остальной рантайм-стейт забега.
    /// </summary>
    public static class TrapInsight
    {
        /// <summary>Идол Чутья: точный тип скрытой ловушки при примеривании (вместо общей сигнатуры).</summary>
        public static bool HasTrapTypeInsight { get; set; }

        /// <summary>Идол Жадности: что ценного скрыто под примериваемой плитой (см. doc-комментарий класса — сейчас без вызывающего кода).</summary>
        public static bool HasTrapContentsInsight { get; set; }
    }
}
