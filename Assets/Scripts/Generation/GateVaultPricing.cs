using System;

namespace Burmalda.Generation
{
    /// <summary>
    /// Размер тайника за Воротами (задача «видимые рычаги, инвариант лавы,
    /// размер награды за Воротами», владелец, 2026-09-04): «задаётся в
    /// покупках, а не в Ключах — тогда при перебалансировке цен в Алтаре
    /// тайники подтянутся сами, а не разъедутся с экономикой». Ориентир:
    /// тайник равен ОДНОЙ ПОЛНОЙ покупке, которую игрок иначе не смог бы
    /// себе позволить — целый второй сундук или целый артефакт, не реролл
    /// и не половина.
    ///
    /// <b>Намеренно НЕ читает <see cref="Altar.Ritual.TalismanOrAmuletChestCost"/>
    /// напрямую</b> — владелец, уточняющий ответ (2026-09-04): «цены Алтаря
    /// будут меняться независимо, и жёсткая связь сделает балансировку
    /// невозможной». <see cref="KeysPerVaultPurchase"/> — ОТДЕЛЬНАЯ, вручную
    /// синхронизируемая константа: стартовое значение 80 совпадает с
    /// сегодняшним <c>Ritual.TalismanOrAmuletChestCost</c> (одна типовая
    /// покупка), но это совпадение чисел на старте, не программная связь.
    /// Когда цены Алтаря поменяются, эту константу подтягивают вручную
    /// вслед за ними — осознанный выбор в пользу раздельной настройки, а не
    /// упущение.
    ///
    /// Шаблоны сегментов хранят число покупок (напр. 1 для короткого
    /// крюка рычаг↔Ворота, 1.5 для длинного — см.
    /// <see cref="SegmentTemplate.GateVaultPurchases"/>), не Ключи напрямую.
    /// </summary>
    public static class GateVaultPricing
    {
        // Стартовое значение — владелец, 2026-09-04 (см. doc-комментарий
        // класса про намеренное отсутствие программной связи с ценами Алтаря).
        public static int KeysPerVaultPurchase = 80;

        /// <summary>Число Ключей тайника на заданное число покупок — округление до целого, к ближайшему.</summary>
        public static int ComputeVaultKeys(double purchases)
        {
            if (purchases <= 0)
                throw new ArgumentOutOfRangeException(nameof(purchases), purchases, "Число покупок тайника должно быть положительным.");

            return (int)Math.Round(purchases * KeysPerVaultPurchase, MidpointRounding.AwayFromZero);
        }
    }
}
