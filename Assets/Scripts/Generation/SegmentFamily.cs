namespace Burmalda.Generation
{
    /// <summary>
    /// Семейство шаблона сегмента (спринт v10-2b): какой навык проверяет участок тоннеля. Селектор
    /// чередует семейства, чтобы участки не повторяли друг друга.
    /// </summary>
    public enum SegmentFamily
    {
        /// <summary>Передышка: почти прямые шаблоны.</summary>
        Relief,

        /// <summary>Змейка со стенами и ловушкой-«дверью» в стене: длинный путь против соблазна срезать.</summary>
        SnakeDoor,

        /// <summary>Змейка, коридоры которой засеяны скрытыми триггерами: крюк и мины сразу.</summary>
        MinedSnake,

        /// <summary>Открытая площадка со множеством скрытых триггеров: безопасные клетки неизвестны, прощупывание стоит времени.</summary>
        Minefield,

        /// <summary>Зал колонн: Стрелы и Камни между колоннами, нужна реакция и чтение линий.</summary>
        PillarHall,
    }
}
