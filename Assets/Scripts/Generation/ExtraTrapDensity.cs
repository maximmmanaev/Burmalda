namespace Burmalda.Generation
{
    /// <summary>
    /// Задача «параметр плотности» (владелец, 2026-09-08): множитель,
    /// добавляющий ловушки ПОВЕРХ авторски расставленных в шаблонах — mutable
    /// static, тот же принцип, что <c>Core.TunnelObstacleGenerator</c>'s
    /// <c>*Share</c>-поля/<see cref="DebugVisuals.TrapRevealFeedback"/>: точную
    /// плотность подбирает владелец на устройстве (<c>DebugVisuals.TrapDensityDebugPanel</c>),
    /// не агент вслепую. Прочитано в <see cref="SegmentRowProvider.ApplyTileType"/> —
    /// каждая обычная (<see cref="SegmentTileType.Open"/>) плита материализуемого
    /// сегмента получает этот шанс стать триггером одной из пяти ловушек,
    /// независимо от того, что заложено в самом шаблоне.
    ///
    /// <b>0 — нейтральное значение</b> (владелец: «стартовое значение —
    /// нейтральное»): ничего не меняется, авторская раскладка шаблонов
    /// применяется как есть — тот же ноль, на котором стоят все
    /// EditMode-тесты каталога (их прогон не должен зависеть от этого
    /// значения). Это отладочный рычаг для стресс-теста плотности на
    /// устройстве, а не собственный баланс — конкретное число не
    /// подбирается здесь.
    /// </summary>
    public static class ExtraTrapDensity
    {
        /// <summary>Шанс, 0..1, что отдельная Open-плита материализуемого сегмента станет дополнительным триггером ловушки.</summary>
        public static float Chance;
    }
}
