namespace Burmalda.Core
{
    /// <summary>
    /// Тип смертельной ловушки. В отличие от <see cref="Tile.IsBlocked"/>
    /// (плита физически непроходима, без последствий), попытка наступить на
    /// плиту с таким типом должна приводить к смерти — см.
    /// <c>GridTraceTrail.LethalTrapTriggered</c>. Все варианты ведут себя
    /// одинаково механически (мгновенная смерть, PRD 9 про d20-испытание
    /// пока не реализовано, см. Burmalda.RunLifecycle) — разделены только
    /// для будущей тематической/визуальной разницы и разных сообщений о смерти.
    /// </summary>
    public enum LethalTrapType
    {
        /// <summary>Статичная ловушка (PRD 4.2): видна заранее, нужно обходить.</summary>
        Pit,

        /// <summary>Статичная ловушка (PRD 4.2): видна заранее, нужно обходить.</summary>
        Lava,

        /// <summary>
        /// Динамическая мгновенная ловушка (PRD 4.2, issue #10): не видна
        /// заранее — плита выглядит обычной, пока не активирована плитой-
        /// триггером (<see cref="Tile.ExplosiveTrapTarget"/>), после чего
        /// становится смертельной, как и остальные варианты.
        /// </summary>
        Explosion,

        /// <summary>
        /// Ловушка «Стрела» (docs/wiki/traps.md, issue #213,
        /// <c>Movement.ArrowWaveTrapSystem</c>): волна по ряду, столбец за
        /// столбцом, тикаемая ХОДАМИ. Отдельный C#-идентификатор от
        /// <see cref="TimedTrapType.Arrow"/> намеренно — та же тема ловушки,
        /// другая механика (одна плита-цель на реальном времени vs. волна по
        /// нескольким плитам на ходах), см. docs/wiki/traps.md «Сверка с уже
        /// существующим кодом». В отличие от <see cref="Pit"/>/<see cref="Lava"/>
        /// — временное состояние: плита возвращается в безопасное
        /// (<see cref="Tile.ClearLethalTrap"/>) через 1 ход, когда волна
        /// проходит дальше.
        /// </summary>
        ArrowWave,

        /// <summary>
        /// Ловушка «Бомба» (docs/wiki/traps.md, issue #214,
        /// <c>Movement.BombTrapSystem</c>): площадь 3×3 вокруг триггера
        /// становится смертельной одномоментно через несколько ходов после
        /// активации, затем возвращается в обычное состояние (владелец:
        /// «плиты не разрушаются» — в отличие от <see cref="Explosion"/>,
        /// который остаётся смертельным навсегда). Отдельный
        /// C#-идентификатор от <see cref="Explosion"/> намеренно — ближайший
        /// по духу прецедент, но не совпадает ни по одному из трёх
        /// параметров (задержка/площадь/обратимость), см. docs/wiki/traps.md
        /// «Сверка с уже существующим кодом».
        /// </summary>
        BombBlast,

        /// <summary>
        /// Ловушка «Лезвия» (docs/wiki/traps.md, issue #215,
        /// <c>Movement.BladeTactTrapSystem</c>): пятитактовый паттерн по
        /// ряду (симметричные пары столбцов от края к центру и обратно),
        /// тикаемый ХОДАМИ, до 2 полных циклов или пока игрок не покинет
        /// ряд. Отдельный C#-идентификатор от <see cref="TimedTrapType.Blade"/>
        /// намеренно — та же тема ловушки, другая механика (одна плита-цель
        /// на реальном времени vs. многотактовый паттерн по ряду на ходах),
        /// см. docs/wiki/traps.md «Сверка с уже существующим кодом». Как и
        /// <see cref="ArrowWave"/> — временное состояние на каждой отдельной
        /// плите такта.
        /// </summary>
        BladeTact,

        /// <summary>
        /// Ловушка «Лава» (docs/wiki/traps.md, issue #216,
        /// <c>Movement.LavaWaveTrapSystem</c>): распространяющаяся волна —
        /// ряды становятся лавой один за другим, начиная с ряда триггера и
        /// назад, пока игрок не пришёл. Отдельный C#-идентификатор от
        /// <see cref="Lava"/> намеренно — <see cref="Lava"/> статичный тип
        /// плиты с генерации (не трогается), эта волна динамическая,
        /// активируется триггером во время забега — принципиально другая
        /// сущность, случайно делящая тему со статичным типом, см.
        /// docs/wiki/traps.md «Сверка с уже существующим кодом». В отличие
        /// от <see cref="ArrowWave"/>/<see cref="BladeTact"/> — постоянное
        /// состояние, как <see cref="Lava"/>/<see cref="Explosion"/>: ряд,
        /// однажды ставший лавой, не возвращается в безопасное (владелец:
        /// «отрезая путь назад» — необратимость и есть смысл ловушки).
        /// </summary>
        LavaWave
    }
}
