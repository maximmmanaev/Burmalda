namespace Burmalda.Core
{
    /// <summary>
    /// Тип смертельной ловушки. В отличие от <see cref="Tile.IsBlocked"/>
    /// (плита физически непроходима, без последствий), попытка наступить на
    /// плиту с таким типом должна приводить к смерти — см.
    /// <c>GridTraceTrail.LethalTrapTriggered</c>. Все варианты ведут себя
    /// одинаково механически (мгновенная смерть, PRD 9 про d20-испытание
    /// пока не реализовано, см. Burmalda.RunLifecycle) — разделены только
    /// для будущей тематической/визуальной разницы и разных сообщений о смерти.
    /// </summary>
    public enum LethalTrapType
    {
        /// <summary>Статичная ловушка (PRD 4.2): видна заранее, нужно обходить.</summary>
        Pit,

        /// <summary>Статичная ловушка (PRD 4.2): видна заранее, нужно обходить.</summary>
        Lava,

        /// <summary>
        /// Динамическая мгновенная ловушка (PRD 4.2, issue #10): не видна
        /// заранее — плита выглядит обычной, пока не активирована плитой-
        /// триггером (<see cref="Tile.ExplosiveTrapTarget"/>), после чего
        /// становится смертельной, как и остальные варианты.
        /// </summary>
        Explosion
    }
}
