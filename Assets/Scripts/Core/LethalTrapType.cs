namespace Burmalda.Core
{
    /// <summary>
    /// Тип смертельной ловушки. В отличие от <see cref="Tile.IsBlocked"/>
    /// (плита физически непроходима, без последствий), попытка наступить на
    /// плиту с таким типом должна приводить к смерти — см.
    /// <c>GridTraceTrail.LethalTrapTriggered</c>. Все варианты ведут себя
    /// одинаково механически (мгновенная смерть, PRD 9 про d20-испытание
    /// пока не реализовано, см. Burmalda.RunLifecycle) — разделены только
    /// для будущей тематической/визуальной разницы и разных сообщений о смерти.
    ///
    /// <b>Владелец, 2026-09-05 («оставить только пять новых ловушек»):</b>
    /// <c>Pit</c> и <c>Explosion</c> (старые механики Спринта 2/#10) убраны
    /// из игры целиком вместе со своими системами (<c>Movement.
    /// ExplosiveTrapArmingSystem</c>) — в игре остаются только Лава (статика)
    /// и пять типов Спринта 13a ниже. Символ 'p'/'e' в
    /// <c>Generation.SegmentTemplateCatalog</c> заменены на 'r'/'x' по месту
    /// (та же роль в раскладке, другая ловушка).
    /// </summary>
    public enum LethalTrapType
    {
        /// <summary>Статичная ловушка (PRD 4.2): видна заранее, нужно обходить.</summary>
        Lava,

        /// <summary>
        /// Ловушка «Стрела» (docs/wiki/traps.md, issue #213,
        /// <c>Movement.ArrowWaveTrapSystem</c>): волна по ряду, столбец за
        /// столбцом, тикаемая ХОДАМИ. В отличие от <see cref="Lava"/> —
        /// временное состояние: плита возвращается в безопасное
        /// (<see cref="Tile.ClearLethalTrap"/>) через 1 ход, когда волна
        /// проходит дальше.
        /// </summary>
        ArrowWave,

        /// <summary>
        /// Ловушка «Бомба» (docs/wiki/traps.md, issue #214,
        /// <c>Movement.BombTrapSystem</c>): площадь 3×3 вокруг триггера
        /// становится смертельной одномоментно через несколько ходов после
        /// активации, затем возвращается в обычное состояние (владелец:
        /// «плиты не разрушаются»).
        /// </summary>
        BombBlast,

        /// <summary>
        /// Ловушка «Лезвия» (docs/wiki/traps.md, issue #215,
        /// <c>Movement.BladeTactTrapSystem</c>): пятитактовый паттерн по
        /// ряду (симметричные пары столбцов от края к центру и обратно),
        /// тикаемый ХОДАМИ, до 2 полных циклов или пока игрок не покинет
        /// ряд. Как и <see cref="ArrowWave"/> — временное состояние на
        /// каждой отдельной плите такта.
        /// </summary>
        BladeTact,

        /// <summary>
        /// Ловушка «Лава» (docs/wiki/traps.md, issue #216,
        /// <c>Movement.LavaWaveTrapSystem</c>): распространяющаяся волна —
        /// ряды становятся лавой один за другим, начиная с ряда триггера и
        /// назад, пока игрок не пришёл. Отдельный C#-идентификатор от
        /// <see cref="Lava"/> намеренно — <see cref="Lava"/> статичный тип
        /// плиты с генерации (не трогается), эта волна динамическая,
        /// активируется триггером во время забега. В отличие от
        /// <see cref="ArrowWave"/>/<see cref="BladeTact"/> — постоянное
        /// состояние, как <see cref="Lava"/>: ряд, однажды ставший лавой, не
        /// возвращается в безопасное (владелец: «отрезая путь назад» —
        /// необратимость и есть смысл ловушки).
        /// </summary>
        LavaWave
    }
}
