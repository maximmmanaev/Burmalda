namespace Burmalda.Core
{
    /// <summary>
    /// Скрытые ловушки (PRD v8 §4.2, issue #163): яма (<see cref="LethalTrapType.Pit"/>)
    /// не видна заранее — вместо точного типа плита несёт только сигнатуру
    /// опасности ("видно, что с плитой что-то не так, но не видно, что
    /// именно" — PRD прямо запрещает различать типы по сигнатуре). Чистая
    /// функция, презентационное правило — саму игровую опасность
    /// (<see cref="GridTraceTrail.CanAdvanceTo"/>/<see cref="GridTraceTrail.TryAdvanceTo"/>)
    /// не трогает, они как были завязаны на <see cref="Tile.LethalTrap"/>
    /// напрямую, так и остались.
    ///
    /// <b>Лава (<see cref="LethalTrapType.Lava"/>) и заблокированные плиты
    /// (<see cref="Tile.IsBlocked"/>) — вне этого правила</b>: PRD прямо
    /// говорит "остаются видимыми как раньше", этот класс их не
    /// классифицирует как скрытые.
    ///
    /// <b>Взрыв (<see cref="LethalTrapType.Explosion"/>) — БЫЛ здесь, БОЛЬШЕ
    /// НЕ ЗДЕСЬ (владелец, задача «разрушение плиты», продолжение,
    /// 2026-09-01):</b> "сработавшая ловушка — угроза, происходящая сейчас,
    /// и скрывать её нельзя, по тому же правилу, что и активную ловушку с
    /// таймингом ниже" — до активации триггером цель физически неотличима от
    /// обычной плиты (<see cref="Tile.ExplosiveTrapTarget"/> хранится на
    /// плите-ТРИГГЕРЕ, не на будущей цели), скрывать нечего; а ПОСЛЕ
    /// активации (<c>Movement.ExplosiveTrapArmingSystem</c> →
    /// <see cref="Tile.TransitionToLethalTrap"/>) это уже не заблаговременное
    /// знание, а реально происходящее прямо сейчас событие — та же логика,
    /// что и для активной ловушки с таймингом ниже, применена симметрично.
    ///
    /// <b>Ловушка с таймингом (стрела/лезвие, issue #45) — тоже вне этого
    /// класса</b>, по двум разным причинам для двух её состояний:
    /// - До активации триггером плита-цель физически не отличима от обычной
    ///   (<see cref="Tile.TimedTrapTarget"/>/<see cref="Tile.TimedTrapKind"/>
    ///   присваиваются только плите-ТРИГГЕРУ при генерации — см.
    ///   <c>Generation.SegmentRowProvider</c> — а не будущей плите-цели; та
    ///   получает своё состояние только в момент активации,
    ///   <c>Movement.TimedTrapSystem</c>) — скрывать сигнатурой нечего, она
    ///   и так уже структурно скрыта.
    /// - Пока плита-цель активна (<see cref="Tile.IsTimedTrapActive"/>) —
    ///   это не заблаговременное знание, а физически происходящая прямо
    ///   сейчас угроза (снаряд/лезвие реально проходит через плиту) —
    ///   скрывать её сигнатурой было бы нечестно по отношению к игроку
    ///   (ему НЕОБХОДИМО видеть, что плита опасна прямо сейчас, чтобы
    ///   успеть увернуться) и противоречило бы самой идее ловушки с
    ///   таймингом (реакция на видимую угрозу, не разведка).
    /// </summary>
    public static class TrapSignature
    {
        /// <summary>
        /// Истинно, если у плиты есть скрытая смертельная ловушка (яма) —
        /// вызывающий код (debug-визуал/HUD) должен показать общую
        /// сигнатуру опасности вместо точного типа, если только у игрока
        /// нет соответствующего Идола (см. <c>Movement.TrapInsight</c>).
        /// Уже активированный взрыв СЮДА больше не входит — см.
        /// doc-комментарий класса, он теперь видим всегда (как активная
        /// ловушка с таймингом), резолверы (<c>DebugVisuals.TileArtKindResolver</c>/
        /// <c>TileDebugColor</c>) обрабатывают его отдельной, безусловной
        /// веткой.
        /// </summary>
        public static bool IsHiddenLethalTrap(Tile tile) =>
            tile != null && tile.LethalTrap == LethalTrapType.Pit;
    }
}
