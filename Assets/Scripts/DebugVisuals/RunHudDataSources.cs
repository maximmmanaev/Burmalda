    ///   Спринт 8 (Camp)". Строить этот контроллер раньше запланированного
    ///   спринта значило бы создавать новую интеграцию, которую эта задача
    ///   явно не просит ("новых игровых систем не создавать").
    ///
    /// <see cref="RunHudOverlay"/> читает оба поля и просто не рисует
    /// соответствующую строку, пока они null — ровно то поведение, которое
    /// задача просит явно для элементов Комнаты Босса ("заложи места в
    /// разметке и оставь пустыми, без заглушечных значений"), примененное
    /// и ко второму обнаруженному по факту пробелу (билд артефактов). Сам
    /// этот класс НИЧЕГО не создаёт и не меняет в игровой логике — только
    /// читает то, что (если) присвоит интеграционный код будущих спринтов.
    ///
    /// <b>Несомые Реликвии и суммарный Вес (PRD v8 §6.3) сюда намеренно НЕ
    /// добавлены</b> — see doc-комментарий <see cref="RunHudOverlay"/> для
    /// причины (в коде нет вообще никакого представления этой механики, не
    /// только незаконченной интеграции — заводить тип-заглушку под неё
    /// значило бы создавать новую систему, что явно запрещено).
    /// </summary>
    public static class RunHudDataSources
    {
        public static Burmalda.BossRoom.BossRoom ActiveBossRoom { get; set; }

        public static RunArtifactLoadout ActiveArtifactLoadout { get; set; }
    }
}
