using Burmalda.Camp;

namespace Burmalda.DebugVisuals
{
    /// <summary>
    /// Хуки под живые экземпляры систем, которых сейчас НИГДЕ в реальной
    /// игре не создают (issue "Задача 2 — отладочный HUD"):
    ///
    /// - <see cref="ActiveBossRoom"/> — <c>BossRoom.BossRoom</c> (Множитель
    ///   Комнаты + дистанция до волны, PRD v8 §8) существует как полностью
    ///   рабочий, покрытый тестами класс (Спринт 11 backlog), но ни один
    ///   Controller в проекте пока не создаёт его экземпляр на вход в
    ///   Комнату — интеграция с забегом (материализация <c>Tile.IsBoss</c>
    ///   → создание Комнаты) относится к Спринту 11, не к этой задаче.
    ///
    /// <b>Состав билда (Амулеты/Талисманы) сюда больше не заводится</b> —
    /// раньше здесь было поле <c>ActiveArtifactLoadout</c>, которое никто не
    /// заполнял (тот же класс пробела). Задача "композиционный корень
    /// RunBootstrap" завела реальный живой <c>Artifacts.RunArtifactLoadout</c>
    /// на каждый забег — потребители читают его напрямую из
    /// <c>Burmalda.Bootstrap.RunBootstrap.Loadout</c>, отдельный статический
    /// мост для него не нужен (Комната Босса своего Controller'а пока не
    /// имеет вовсе, поэтому для неё мост ниже остаётся).
    ///
    /// <see cref="RunHudOverlay"/> читает <see cref="ActiveBossRoom"/> и
    /// просто не рисует соответствующую строку, пока оно null — то
    /// поведение, которое задача просит явно для элементов Комнаты Босса
    /// ("заложи места в разметке и оставь пустыми, без заглушечных
    /// значений"). Сам этот класс НИЧЕГО не создаёт и не меняет в игровой
    /// логике — только читает то, что (если) присвоит интеграционный код
    /// будущих спринтов.
    ///
    /// <b>Несомые Реликвии и суммарный Вес (PRD v8 §6.3) сюда намеренно НЕ
    /// добавлены</b> — see doc-комментарий <see cref="RunHudOverlay"/> для
    /// причины (в коде нет вообще никакого представления этой механики, не
    /// только незаконченной интеграции — заводить тип-заглушку под неё
    /// значило бы создавать новую систему, что явно запрещено).
    /// </summary>
    public static class RunHudDataSources
    {
        public static Burmalda.BossRoom.BossRoom ActiveBossRoom { get; set; }

        /// <summary>
        /// Разбивка последней конвертации Маны/Ключей в Монеты при успешном
        /// возврате в Лагерь (PRD v9 раздел 5/10, задача по экономике "Мана
        /// как доход забега"). В отличие от <see cref="ActiveBossRoom"/>/
        /// <see cref="ActiveArtifactLoadout"/> — источник ЖИВОЙ:
        /// <c>Camp.CampController</c> уже создаёт и владеет
        /// <c>Camp.ReturnJourneySystem</c> на каждый забег, только само
        /// событие <c>Returned</c> раньше никто не слушал. Присваивается
        /// <see cref="ReturnConversionHudBridge"/> при каждом успешном
        /// возврате; null до первого возврата за сессию (не за забег —
        /// значение намеренно НЕ сбрасывается на новый забег, чтобы
        /// результат последнего похода оставался виден на экране Лагеря).
        /// </summary>
        public static ReturnConversionResult? LastReturnResult { get; set; }
    }
}
