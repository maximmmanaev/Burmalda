    /// <summary>
    /// Хуки под живые экземпляры систем, которых сейчас НИГДЕ в реальной
    /// игре не создают (issue "Задача 2 — отладочный HUD"):
    ///
    /// - <see cref="ActiveBossRoom"/> — <c>BossRoom.BossRoom</c> (Множитель
    ///   Комнаты + дистанция до волны, PRD v8 §8) существует как полностью
    ///   рабочий, покрытый тестами класс (Спринт 11 backlog), но ни один
    ///   Controller в проекте пока не создаёт его экземпляр на вход в
    ///   Комнату — интеграция с забегом (материализация <c>Tile.IsBoss</c>
    ///   → создание Комнаты) относится к Спринту 11, не к этой задаче.
    /// - <see cref="ActiveArtifactLoadout"/> — <c>Artifacts.RunArtifactLoadout</c>
    ///   (состав билда — Амулеты/Талисманы по Id) тоже полностью рабочий
    ///   класс, уже принимается параметром в <c>Altar.Ritual</c>, но ни один
    ///   Controller не держит его экземпляр НА ЗАБЕГ — см. doc-комментарий
